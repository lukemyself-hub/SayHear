import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";

import { describe, expect, it } from "vitest";

import {
  protectedSurfaceDdlViolations,
  runSchemaExtensionGuard,
  type SchemaExtensionGuardIo,
} from "../scripts/check-schema-extensions.ts";

function sha256Text(value: string): string {
  return createHash("sha256").update(value, "utf8").digest("hex");
}

function fakeIo(files: Readonly<Record<string, string>>): SchemaExtensionGuardIo {
  return {
    repositoryRoot: "/repo",
    readFile: async (path) => {
      const contents = files[path];
      if (contents === undefined) throw new Error(`missing fake file ${path}`);
      return contents;
    },
    fileExists: async (path) => path in files,
  };
}

describe("protected-surface DDL deny-list", () => {
  it("allows the admitted additive nullable column and index", () => {
    const sql = [
      "-- a comment mentioning generation_commands and purge_markers",
      "ALTER TABLE generation_commands",
      "  ADD COLUMN request_timezone TEXT;",
      "CREATE INDEX conversation_events_recent_context_idx",
      "  ON conversation_events(user_id, created_at);",
    ].join("\n");
    expect(protectedSurfaceDdlViolations("0069.sql", sql)).toEqual([]);
  });

  it("rejects a NOT NULL protected-surface column addition", () => {
    const violations = protectedSurfaceDdlViolations(
      "bad.sql",
      "ALTER TABLE generation_commands ADD COLUMN request_timezone TEXT NOT NULL;",
    );
    expect(violations).toHaveLength(1);
    expect(violations[0]).toMatch(/must be nullable/);
  });

  it("rejects column additions that imply NOT NULL without the literal", () => {
    for (const sql of [
      "ALTER TABLE generation_commands ADD COLUMN request_timezone TEXT PRIMARY KEY;",
      "ALTER TABLE generation_commands ADD COLUMN seq INTEGER GENERATED ALWAYS AS IDENTITY;",
      "ALTER TABLE generation_commands ADD COLUMN seq INTEGER GENERATED BY DEFAULT AS IDENTITY;",
    ]) {
      const violations = protectedSurfaceDdlViolations("bad.sql", sql);
      expect(violations).toHaveLength(1);
      expect(violations[0]).toMatch(/must be nullable/);
    }
  });

  it("allows an index that targets a protected relation but rejects a DROP INDEX", () => {
    expect(
      protectedSurfaceDdlViolations(
        "ok.sql",
        "CREATE INDEX model_role_definitions_role_idx ON model_role_definitions(role);",
      ),
    ).toEqual([]);
    expect(
      protectedSurfaceDdlViolations(
        "bad.sql",
        "DROP INDEX model_role_definitions_role_idx;",
      ).length,
    ).toBeGreaterThan(0);
  });

  it("rejects an index statement that merely names a protected relation", () => {
    // The protected name is the index name, but the index targets a safe table.
    const violations = protectedSurfaceDdlViolations(
      "bad.sql",
      "CREATE INDEX generation_commands ON conversation_events(user_id);",
    );
    expect(violations).toHaveLength(1);
    expect(violations[0]).toMatch(/without targeting it/);
  });

  it("treats the operation and migration ledgers as protected surfaces", () => {
    for (const relation of [
      "schema_migrations",
      "owner_purge_operational_metadata",
    ]) {
      expect(
        protectedSurfaceDdlViolations("bad.sql", `DROP TABLE ${relation};`).length,
      ).toBeGreaterThan(0);
    }
  });

  it("allows a plain nullable column addition on a protected relation", () => {
    expect(
      protectedSurfaceDdlViolations(
        "ok.sql",
        "ALTER TABLE generation_commands ADD COLUMN request_timezone TEXT;",
      ),
    ).toEqual([]);
  });

  it("rejects destructive or mutating DDL against a protected relation", () => {
    for (const sql of [
      "ALTER TABLE model_role_rollout_pins DROP COLUMN status;",
      "TRUNCATE TABLE provider_egress_policy_versions;",
      "DELETE FROM purge_markers;",
      "UPDATE workflow_commands SET status = 'done';",
      "ALTER TABLE provider_egress_consents RENAME TO other;",
    ]) {
      expect(protectedSurfaceDdlViolations("bad.sql", sql).length).toBeGreaterThan(0);
    }
  });

  it("rejects an additive statement that is not a column add or index", () => {
    const violations = protectedSurfaceDdlViolations(
      "bad.sql",
      "ALTER TABLE model_role_definitions ADD CONSTRAINT fk FOREIGN KEY (role) REFERENCES x(role);",
    );
    expect(violations).toHaveLength(1);
  });

  it("ignores statements with no protected relation", () => {
    expect(
      protectedSurfaceDdlViolations(
        "neutral.sql",
        "CREATE TABLE recent_context_policies (policy_version TEXT PRIMARY KEY);",
      ),
    ).toEqual([]);
  });
});

describe("generation stage CHECK widening exception (#314, ADR-0094)", () => {
  const drop =
    "ALTER TABLE generation_commands DROP CONSTRAINT generation_commands_generation_stage_check;";
  const add = (values: string) =>
    `ALTER TABLE generation_commands ADD CONSTRAINT generation_commands_generation_stage_check CHECK (generation_stage IN (${values}));`;
  const existing = "'decision', 'action_finalization', 'proactive_followup'";
  const STAGE_FILE = "0071_history_answer_generation_stage.sql";

  it("admits widening the stage CHECK by exactly the history_answer value", () => {
    const sql = [drop, add(`${existing}, 'history_answer'`)].join("\n");
    expect(protectedSurfaceDdlViolations(STAGE_FILE, sql)).toEqual([]);
  });

  it("still admits the committed 0071 migration", () => {
    const sql = readFileSync(
      new URL(`../packages/data/migrations/${STAGE_FILE}`, import.meta.url),
      "utf8",
    );
    expect(protectedSurfaceDdlViolations(STAGE_FILE, sql)).toEqual([]);
  });

  it("rejects a DROP of the stage CHECK that is not immediately followed by the admitted ADD", () => {
    // Alone: the constraint would simply be gone.
    expect(protectedSurfaceDdlViolations(STAGE_FILE, drop)).toHaveLength(1);
    // Followed by something else first.
    expect(
      protectedSurfaceDdlViolations(
        STAGE_FILE,
        [drop, "CREATE TABLE unrelated (id INTEGER);", add(`${existing}, 'history_answer'`)].join("\n"),
      ).length,
    ).toBeGreaterThanOrEqual(1);
    // Followed by an ADD that does not qualify: both statements are refused.
    expect(
      protectedSurfaceDdlViolations(STAGE_FILE, [drop, add(existing)].join("\n")),
    ).toHaveLength(2);
  });

  it("rejects an ADD whose value set is not exactly the frozen stages plus history_answer", () => {
    const pair = (values: string) => [drop, add(values)].join("\n");
    // Back to the three frozen values only: history_answer rows would violate it.
    expect(protectedSurfaceDdlViolations(STAGE_FILE, pair(existing)).length).toBeGreaterThanOrEqual(1);
    expect(
      protectedSurfaceDdlViolations(STAGE_FILE, pair(`${existing}, 'history_answer', 'surprise'`)).length,
    ).toBeGreaterThanOrEqual(1);
    expect(
      protectedSurfaceDdlViolations(STAGE_FILE, pair("'decision', 'history_answer'")).length,
    ).toBeGreaterThanOrEqual(1);
    expect(
      protectedSurfaceDdlViolations(
        STAGE_FILE,
        pair(`${existing}, 'history_answer', 'history_answer'`),
      ).length,
    ).toBeGreaterThanOrEqual(1);
    // An ADD with no DROP before it is not the admitted pair either.
    expect(
      protectedSurfaceDdlViolations(STAGE_FILE, add(`${existing}, 'history_answer'`)),
    ).toHaveLength(1);
  });

  it("does not lend the exception to any other migration file", () => {
    const sql = [drop, add(`${existing}, 'history_answer'`)].join("\n");
    for (const other of ["0071.sql", "0099_another_stage.sql", "0072_history_recall_results.sql"]) {
      expect(protectedSurfaceDdlViolations(other, sql)).toHaveLength(2);
    }
  });

  it("rejects narrowing, an unknown value, or any other generation_commands constraint", () => {
    expect(
      protectedSurfaceDdlViolations(STAGE_FILE, add("'decision', 'history_answer'")),
    ).toHaveLength(1);
    expect(
      protectedSurfaceDdlViolations(STAGE_FILE, add(`${existing}, 'history_answer', 'surprise'`)),
    ).toHaveLength(1);
    expect(
      protectedSurfaceDdlViolations(
        "bad.sql",
        "ALTER TABLE generation_commands DROP CONSTRAINT generation_commands_action_receipt_snapshot_check;",
      ),
    ).toHaveLength(1);
    expect(
      protectedSurfaceDdlViolations(
        "bad.sql",
        "ALTER TABLE generation_commands DROP CONSTRAINT generation_commands_generation_stage_check, DROP COLUMN status;",
      ),
    ).toHaveLength(1);
  });
});

describe("schema-extension file guard", () => {
  const registry = [
    {
      store: "business" as const,
      name: "0001_ok.sql",
      sha256: sha256Text("ALTER TABLE generation_commands ADD COLUMN note TEXT;"),
      justification: "test",
    },
    {
      store: "business" as const,
      name: "0002_mismatch.sql",
      sha256: "a".repeat(64),
      justification: "test",
    },
    {
      store: "business" as const,
      name: "0003_pending.sql",
      sha256: "b".repeat(64),
      justification: "test",
    },
  ];

  it("verifies landed hashes, reports pending entries, and fails a hash drift", async () => {
    const result = await runSchemaExtensionGuard(
      fakeIo({
        "/repo/packages/data/migrations/0001_ok.sql":
          "ALTER TABLE generation_commands ADD COLUMN note TEXT;",
        "/repo/packages/data/migrations/0002_mismatch.sql": "SELECT 1;",
      }),
      registry,
    );

    expect(result.ok).toBe(false);
    expect(result.pendingExtensions.map((pin) => pin.name)).toEqual([
      "0003_pending.sql",
    ]);
    expect(result.appliedExtensions.map((pin) => pin.name)).toEqual([
      "0001_ok.sql",
      "0002_mismatch.sql",
    ]);
    expect(result.failures).toHaveLength(1);
    expect(result.failures[0]).toMatch(/0002_mismatch\.sql/);
  });

  it("fails a landed file that violates the protected-surface deny-list", async () => {
    const sql = "ALTER TABLE model_role_rollout_pins DROP COLUMN status;";
    const result = await runSchemaExtensionGuard(
      fakeIo({
        "/repo/packages/data/migrations/0001_ok.sql": sql,
      }),
      [
        {
          store: "business",
          name: "0001_ok.sql",
          sha256: sha256Text(sql),
          justification: "test",
        },
      ],
    );
    expect(result.ok).toBe(false);
    expect(result.failures[0]).toMatch(/destructive or mutating DDL/);
  });

  it("treats a missing purge-marker file as pending and a wrong hash as a failure", async () => {
    const markerName = "0001_purge_marker.sql";
    const markerPath = `/repo/packages/data/migrations-purge-marker/${markerName}`;

    const pending = await runSchemaExtensionGuard(
      fakeIo({}),
      [
        {
          store: "purge-marker",
          name: markerName,
          sha256: "a".repeat(64),
          justification: "test",
        },
      ],
    );
    expect(pending.ok).toBe(true);
    expect(pending.pendingExtensions.map((pin) => pin.name)).toEqual([markerName]);

    const drift = await runSchemaExtensionGuard(
      fakeIo({ [markerPath]: "CREATE TABLE purge_markers (user_id UUID PRIMARY KEY);" }),
      [
        {
          store: "purge-marker",
          name: markerName,
          sha256: "a".repeat(64),
          justification: "test",
        },
      ],
    );
    expect(drift.ok).toBe(false);
    expect(drift.failures[0]).toMatch(/does not match the file hash/);
  });
});
