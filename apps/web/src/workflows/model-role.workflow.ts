import {
  assertWorkflowSafe,
  asGenerationCommandId,
  asModelRunAttemptId,
  asUserId,
  ONE_A_3B_G1_ENABLED_ROLES,
  ONE_A_3B_MODEL_ROLES,
  ONE_A_3B_ROLE_POLICY_VERSION,
  RecoveryGateClosedError,
  runEpisodeBuildAttempt,
  runNarrativeValidationAttempt,
  runReflectionAttempt,
  type ModelRoleAttemptKind,
  type OneA3bModelRole,
} from "@sayhear/application";

import { createServerComposition } from "../server-composition";

export type ModelRoleWorkflowInput = Readonly<{
  workflowCommandId: string;
  subjectId: string;
  sourceRevision: number;
  policyVersion: string;
  expectedDataEpoch: number;
  modelRole: OneA3bModelRole;
  generationCommandId: string;
  modelRunAttemptId: string;
  attemptNo: number;
  attemptKind: ModelRoleAttemptKind;
  rolloutPin: string;
}>;

export type ModelRoleWorkflowResult = Readonly<{
  modelRole: OneA3bModelRole;
  outcome: "succeeded" | "retry_scheduled" | "failed" | "discarded";
  errorCode: string | null;
}>;

function isModelRole(value: string): value is OneA3bModelRole {
  return (ONE_A_3B_MODEL_ROLES as readonly string[]).includes(value);
}

function isG1ModelRole(value: OneA3bModelRole): boolean {
  return (ONE_A_3B_G1_ENABLED_ROLES as readonly string[]).includes(value);
}

function isAttemptKind(value: string): value is ModelRoleAttemptKind {
  return (
    value === "initial" ||
    value === "technical_retry" ||
    value === "schema_repair"
  );
}

function assertNonEmptyString(value: unknown, field: string): asserts value is string {
  if (typeof value !== "string" || value.trim() === "") {
    throw new Error(`Model role ${field} must be non-empty.`);
  }
}

/**
 * Validate the content-free envelope before it enters a durable Workflow.
 * The outbox payload is generated by the database, but the Workflow boundary
 * still treats it as untrusted input and keeps later-stage roles closed.
 */
export function assertModelRoleWorkflowInput(
  input: ModelRoleWorkflowInput,
): void {
  assertWorkflowSafe(input, "model-role-input");
  for (const [field, value] of [
    ["workflowCommandId", input.workflowCommandId],
    ["subjectId", input.subjectId],
    ["policyVersion", input.policyVersion],
    ["generationCommandId", input.generationCommandId],
    ["modelRunAttemptId", input.modelRunAttemptId],
    ["rolloutPin", input.rolloutPin],
  ] as const) {
    assertNonEmptyString(value, field);
  }
  if (!isModelRole(input.modelRole)) {
    throw new Error(`Unknown 1A.3b model role: ${input.modelRole}.`);
  }
  if (!isG1ModelRole(input.modelRole)) {
    throw new Error(
      `Model role ${input.modelRole} is deferred until a later release stage.`,
    );
  }
  if (input.attemptKind === "schema_repair") {
    throw new Error("schema_repair is not enabled for G1 roles.");
  }
  if (input.policyVersion !== ONE_A_3B_ROLE_POLICY_VERSION) {
    throw new Error(
      `Model role policy ${input.policyVersion} is not the released ${ONE_A_3B_ROLE_POLICY_VERSION}.`,
    );
  }
  if (!Number.isSafeInteger(input.sourceRevision) || input.sourceRevision < 0) {
    throw new Error("Model role sourceRevision must be a non-negative safe integer.");
  }
  if (
    !Number.isSafeInteger(input.expectedDataEpoch) ||
    input.expectedDataEpoch <= 0
  ) {
    throw new Error("Model role expectedDataEpoch must be a positive safe integer.");
  }
  if (!Number.isSafeInteger(input.attemptNo) || input.attemptNo <= 0) {
    throw new Error("Model role attemptNo must be a positive safe integer.");
  }
  if (!isAttemptKind(input.attemptKind)) {
    throw new Error(`Unknown model role attempt kind: ${input.attemptKind}.`);
  }
}

function resultFor(
  modelRole: OneA3bModelRole,
  outcome: ModelRoleWorkflowResult["outcome"],
  errorCode: string | null,
): ModelRoleWorkflowResult {
  const result = { modelRole, outcome, errorCode } as const;
  assertWorkflowSafe(result, "model-role-result");
  return result;
}

function mapAttemptOutcome(
  outcome: string,
): ModelRoleWorkflowResult["outcome"] {
  switch (outcome) {
    case "built":
    case "completed":
      return "succeeded";
    case "retryable_failed":
      return "retry_scheduled";
    case "stale_superseded":
    case "fenced":
    case "incomplete":
      return "discarded";
    default:
      return "failed";
  }
}

export async function modelRoleWorkflow(
  input: ModelRoleWorkflowInput,
): Promise<ModelRoleWorkflowResult> {
  "use workflow";
  assertModelRoleWorkflowInput(input);
  return await runModelRoleStep(input);
}

async function runModelRoleStep(
  input: ModelRoleWorkflowInput,
): Promise<ModelRoleWorkflowResult> {
  "use step";
  const composition = createServerComposition();
  const userId = asUserId(input.subjectId);
  await composition.modelRoleCommandService.verifyActiveG1Release?.();

  try {
    // The model-role outbox subject is the owner ID. Check the recovery fence
    // before reconstructing any frozen request or reading private content.
    await composition.recoveryGate.requireOpen(userId);
  } catch (error) {
    if (!(error instanceof RecoveryGateClosedError)) {
      throw error;
    }
    if (error.result.status === "unavailable") {
      throw error;
    }
    await composition.modelRoleCommandService.discardAttempt({
      userId,
      generationCommandId: asGenerationCommandId(input.generationCommandId),
      modelRunAttemptId: asModelRunAttemptId(input.modelRunAttemptId),
      reason: "recovery_closed",
      now: composition.clock(),
    });
    return resultFor(input.modelRole, "discarded", "recovery_closed");
  }

  const configuration = composition.modelRoleCommandService.configuration(
    input.modelRole,
  );
  if (!configuration) {
    await composition.modelRoleCommandService.discardAttempt({
      userId,
      generationCommandId: asGenerationCommandId(input.generationCommandId),
      modelRunAttemptId: asModelRunAttemptId(input.modelRunAttemptId),
      reason: "runtime_disabled",
      now: composition.clock(),
    });
    return resultFor(input.modelRole, "discarded", "runtime_disabled");
  }

  const recovered = await composition.modelRoleCommandService.recoverAttempt?.({
    userId,
    generationCommandId: asGenerationCommandId(input.generationCommandId),
    modelRunAttemptId: asModelRunAttemptId(input.modelRunAttemptId),
    now: composition.clock(),
  });
  if (recovered?.outcome === "settled") {
    return resultFor(
      input.modelRole,
      recovered.terminalOutcome,
      recovered.terminalOutcome === "discarded" ? "attempt_settled" : null,
    );
  }
  const attempt =
    recovered?.outcome === "ready"
      ? {
          ...input,
          generationCommandId: String(recovered.generationCommandId),
          modelRunAttemptId: String(recovered.modelRunAttemptId),
          attemptNo: recovered.attemptNo,
          attemptKind: recovered.attemptKind,
        }
      : input;

  const readiness = await composition.modelRoleCommandService.validateAttempt({
    userId,
    generationCommandId: asGenerationCommandId(attempt.generationCommandId),
    modelRunAttemptId: asModelRunAttemptId(attempt.modelRunAttemptId),
    role: attempt.modelRole,
    attemptNo: attempt.attemptNo,
    attemptKind: attempt.attemptKind,
    rolloutPin: attempt.rolloutPin,
    currentSourceRevision: attempt.sourceRevision,
    expectedDataEpoch: attempt.expectedDataEpoch,
    now: composition.clock(),
  });
  if (readiness.outcome !== "ready") {
    return resultFor(
      attempt.modelRole,
      "discarded",
      readiness.reason ?? "attempt_not_ready",
    );
  }

  if (input.modelRole === "episode.build") {
    const dependencies = composition.episodeEntrypointDependencies(
      input.workflowCommandId,
    );
    const result = await runEpisodeBuildAttempt({
      ...dependencies,
      command: {
        workflowCommandId: input.workflowCommandId,
        generationCommandId: attempt.generationCommandId,
        modelRunAttemptId: attempt.modelRunAttemptId,
        attemptNo: attempt.attemptNo,
        attemptKind: attempt.attemptKind,
        rolloutPin: attempt.rolloutPin,
        sourceRevision: attempt.sourceRevision,
        policyVersion: attempt.policyVersion,
        expectedDataEpoch: attempt.expectedDataEpoch,
      },
      recoveryGate: composition.recoveryGate,
      recoveryOwnerId: userId,
    });
    return resultFor(
      attempt.modelRole,
      mapAttemptOutcome(result.outcome),
      result.errorCode,
    );
  }

  if (input.modelRole === "reflection.daily" || input.modelRole === "reflection.weekly") {
    const dependencies = composition.reflectionEntrypointDependencies(
      input.workflowCommandId,
    );
    const result = await runReflectionAttempt({
      dependencies,
      command: {
        generationCommandId: attempt.generationCommandId,
        modelRunAttemptId: attempt.modelRunAttemptId,
        attemptNo: attempt.attemptNo,
        attemptKind: attempt.attemptKind,
        rolloutPin: attempt.rolloutPin,
      },
      recoveryGate: composition.recoveryGate,
      recoveryOwnerId: userId,
    });
    return resultFor(
      attempt.modelRole,
      mapAttemptOutcome(result.outcome),
      result.errorCode ?? result.rejectionCode,
    );
  }

  const dependencies = composition.narrativeValidationEntrypointDependencies();
  const result = await runNarrativeValidationAttempt({
    dependencies,
    command: {
      generationCommandId: attempt.generationCommandId,
      modelRunAttemptId: attempt.modelRunAttemptId,
      attemptNo: attempt.attemptNo,
      attemptKind: attempt.attemptKind,
      rolloutPin: attempt.rolloutPin,
    },
    recoveryGate: composition.recoveryGate,
    recoveryOwnerId: userId,
  });
  return resultFor(
    attempt.modelRole,
    mapAttemptOutcome(result.outcome),
    result.errorCode ?? result.rejectionCode,
  );
}
